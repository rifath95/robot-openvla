"""Loopback-only launcher for clickable Replay links in a local sweep REPORT.md."""

from common.output_layout import output_path, resolve_output_path
import argparse
from http.server import BaseHTTPRequestHandler,ThreadingHTTPServer
import html
import json
from pathlib import Path
import secrets
import subprocess
import sys
import threading
from urllib.parse import urlparse,parse_qs,urlencode
from common.paths import PROJECT_ROOT
from cloud.sweep_plan import validate_saved


def configure(folder,base_url,token):
    payload=json.loads((folder/'results.json').read_text());specs=validate_saved(payload)
    if payload['plan']['task']!='multi_color_touch':raise ValueError('Replay buttons currently support multi-cube sweep reports')
    rows=payload['trials']
    allowed={r['directory'] for r in rows if (folder/r['directory']/'summary.json').is_file()}
    if len(allowed)!=len(rows):raise ValueError('Restore all trial folders before enabling Replay links')
    from analysis.multi_color_report import write_report
    urls={name:base_url+'/replay?'+urlencode(dict(trial=name,token=token)) for name in allowed}
    write_report(folder,payload['plan'],rows,payload.get('launcher_error'),replay_urls=urls)
    return allowed


class Launcher:
    def __init__(self,folder,allowed,token):
        self.folder=folder;self.allowed=allowed;self.token=token;self.process=None;self.lock=threading.Lock()
    def launch(self,trial,token):
        if not secrets.compare_digest(token,self.token):return 403,'Replay link expired. Use the current report generated by the launcher.'
        if trial not in self.allowed:return 404,'Unknown trial.'
        with self.lock:
            if self.process is not None and self.process.poll() is None:
                return 409,'A replay window is already open. Close it before choosing another run.'
            # The mjpython shebang cannot handle spaces in the repository path.
            # Invoke its script through Python, as the normal simulator viewer does.
            self.process=subprocess.Popen([str(PROJECT_ROOT/'.venv/bin/python'),str(PROJECT_ROOT/'.venv/bin/mjpython'),'-m','simulation.replay_run',
                str(self.folder/trial),'--start-immediately'],cwd=PROJECT_ROOT)
        return 200,'Replay opened on your Mac. You can return to the report and close this browser tab.'


def handler(launcher):
    class Handler(BaseHTTPRequestHandler):
        def do_GET(self):
            parsed=urlparse(self.path);query=parse_qs(parsed.query)
            if parsed.path!='/replay':code,message=404,'Use a Replay link from REPORT.md.'
            else:
                trial=query.get('trial',[''])[0];token=query.get('token',[''])[0]
                try:code,message=launcher.launch(trial,token)
                except OSError as error:
                    print(f'Could not start replay: {error}',file=sys.stderr,flush=True)
                    code,message=500,'Could not open MuJoCo. Check the launcher terminal.'
            body=('<!doctype html><html><body><p>'+html.escape(message)+'</p></body></html>').encode()
            self.send_response(code);self.send_header('Content-Type','text/html; charset=utf-8')
            self.send_header('Cache-Control','no-store');self.send_header('Referrer-Policy','no-referrer')
            self.send_header('Content-Length',str(len(body)));self.end_headers();self.wfile.write(body)
        def log_message(self,*args):pass  # Do not log the per-session link token.
    return Handler


def serve(folder,port=8765):
    folder=resolve_output_path(folder).resolve()
    if not folder.is_relative_to((PROJECT_ROOT/'outputs').resolve()):raise ValueError('Select a sweep folder under outputs/')
    token=secrets.token_urlsafe(32);launcher=Launcher(folder,set(),token)
    with ThreadingHTTPServer(('127.0.0.1',port),handler(launcher)) as server:
        base=f'http://127.0.0.1:{server.server_port}'
        launcher.allowed=configure(folder,base,token)
        print('Replay buttons ready:',folder/'REPORT.md',flush=True)
        print('Keep this launcher running; open Markdown Preview and click ▶ Replay. Ctrl+C stops the launcher.',flush=True)
        try:server.serve_forever()
        except KeyboardInterrupt:pass


def main():
    p=argparse.ArgumentParser(description=__doc__);p.add_argument('--sweep',type=Path,required=True)
    p.add_argument('--port',type=int,default=8765);a=p.parse_args();serve(a.sweep,a.port)

if __name__=='__main__':main()

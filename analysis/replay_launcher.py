def configure(folder,base_url,token):
    payload=json.loads((folder/'results.json').read_text());specs=validate_saved(payload)
    if payload['plan']['task']!='multi_color_touch':raise ValueError('Replay buttons currently support multi-cube sweep reports')
    rows=payload['trials']
    allowed={r['directory'] for r in rows if (folder/r['directory']/'summary.json').is_file()}
    if len(allowed)!=len(rows):raise ValueError('Restore all trial folders before enabling Replay links')
    from analysis.multi_color_report import write_report
    urls={name:replay_url(folder/name,base_url=base_url,token=token) for name in allowed}
    write_report(folder,payload['plan'],rows,payload.get('launcher_error'),replay_urls=urls)
    return allowed


class Launcher:
    def __init__(self,folder,allowed,token):
        self.folder=folder;self.allowed=allowed;self.token=token;self.process=None;self.lock=threading.Lock()
    def launch_run(self,name,token,mode='poses'):
        if not secrets.compare_digest(token.encode(),self.token.encode()):return 403,'Invalid replay link. Refresh its local report.'
        if mode not in ('poses','actions'):return 400,'Unknown replay mode.'
        relative=Path(name)
        if relative.is_absolute() or '..' in relative.parts:return 400,'Invalid replay path.'
        folder=resolve_output_path(PROJECT_ROOT/relative).resolve()
        roots=(PROJECT_ROOT/'outputs',PROJECT_ROOT/'datasets')
        if not any(folder.is_relative_to(root) for root in roots):return 403,'Select a recorded run under outputs/ or datasets/.'
        if not folder.is_dir():return 404,'Run not found. Restore or download its recording first.'
        if mode=='actions':
            ready=(folder/'transitions.jsonl').is_file() and (folder/'initial_state.npz').is_file() and (folder/'episode.json').is_file()
        else:ready=any(folder.glob('step_*/*.npz'))
        if not ready:return 404,'No saved recording available for this replay mode.'
        return self._open(folder,mode)

    def _open(self,folder,mode):
        with self.lock:
            if self.process is not None and self.process.poll() is None:
                return 409,'A replay window is already open. Close it before choosing another run.'
            module='simulation.action_replay' if mode=='actions' else 'simulation.replay_run'
            self.process=subprocess.Popen([str(PROJECT_ROOT/'.venv/bin/python'),str(PROJECT_ROOT/'.venv/bin/mjpython'),'-m',module,
                str(folder),'--start-immediately'],cwd=PROJECT_ROOT)
        return 200,'Replay opened on your Mac. You can return to the report and close this browser tab.'

    def launch(self,trial,token):
        if not secrets.compare_digest(token.encode(),self.token.encode()):return 403,'Replay link expired. Use the current report generated by the launcher.'
        if trial not in self.allowed and 'trials/'+trial in self.allowed:trial='trials/'+trial
        if trial not in self.allowed:return 404,'Unknown trial.'
        return self._open(self.folder/trial,'poses')


def handler(launcher):
    class Handler(BaseHTTPRequestHandler):
        def do_GET(self):
            parsed=urlparse(self.path);query=parse_qs(parsed.query)
            if parsed.path!='/replay':code,message=404,'Use a Replay link from REPORT.md.'
            else:
                trial=query.get('trial',[''])[0];token=query.get('token',[''])[0]
                try:
                    if 'run' in query:code,message=launcher.launch_run(query['run'][0],token,query.get('mode',['poses'])[0])
                    else:code,message=launcher.launch(trial,token)
                except OSError as error:
                    print(f'Could not start replay: {error}',file=sys.stderr,flush=True)
                    code,message=500,'Could not open MuJoCo. Check the launcher terminal.'
            body=('<!doctype html><html><body><p>'+html.escape(message)+'</p></body></html>').encode()
            self.send_response(code);self.send_header('Content-Type','text/html; charset=utf-8')
            self.send_header('Cache-Control','no-store');self.send_header('Referrer-Policy','no-referrer')
            self.send_header('Content-Length',str(len(body)));self.end_headers();self.wfile.write(body)
        def log_message(self,*args):pass  # Do not log the local link token.
    return Handler


def refresh(folder,base_url=None,token=None):
    """Rebind only local derived reports, leaving recordings and manifests intact."""
    from common.replay_links import add_trial_replays,replay_buttons
    folder=Path(folder).resolve()
    if (folder/'manifest.json').is_file() and (folder/'WATCH_TRAJECTORIES.md').is_file():
        from data_tools.dataset_paths import write_trajectory_index
        rows=json.loads((folder/'manifest.json').read_text()).get('episodes',[])
        if rows and all(isinstance(r,dict) and {'id','split','episode','passed'}<=r.keys() for r in rows):write_trajectory_index(folder,rows)
    if (folder/'results.json').is_file() and (folder/'REPORT.md').is_file():
        payload=json.loads((folder/'results.json').read_text());rows=payload['trials']
        if payload['plan'].get('task')=='multi_color_touch':
            # Partial sweeps still get links; the launcher checks recording availability on click.
            from analysis.multi_color_report import write_report
            urls={r['directory']:replay_url(folder/r['directory'],base_url=base_url,token=token) for r in rows}
            write_report(folder,payload['plan'],rows,payload.get('launcher_error'),replay_urls=urls or None)
        else:
            p=folder/'REPORT.md';p.write_text(add_trial_replays(folder,rows,p.read_text()))
    report=folder/'RUN_REPORT.md'
    if report.is_file():
        text=report.read_text();buttons=replay_buttons(folder)
        if buttons:
            text=re.sub(r'\n\[▶ Replay\]\(http[^\n]+\)\n','\n',text)
            lines=text.splitlines();lines[2:2]=[buttons,''];report.write_text('\n'.join(lines)+'\n')


def serve(folder=None,port=None,dataset=None):
    settings=context();port=settings['port'] if port is None else port
    launcher=Launcher(PROJECT_ROOT,set(),settings['token'])
    with ThreadingHTTPServer(('127.0.0.1',port),handler(launcher)) as server:
        settings['port']=server.server_port;CONFIG.write_text(json.dumps(settings)+'\n')
        base=f'http://127.0.0.1:{server.server_port}'
        selected=[resolve_output_path(p).resolve() for p in (folder,dataset) if p is not None]
        if not selected:
            selected=list((PROJECT_ROOT/'datasets').glob('*/WATCH_TRAJECTORIES.md'))
            selected=[p.parent for p in selected]
            selected+=list((PROJECT_ROOT/'outputs/sweeps').glob('*/REPORT.md'))
            selected=[p.parent if p.name=='REPORT.md' else p for p in selected]
        for p in selected:
            if not any(p.is_relative_to(root) for root in (PROJECT_ROOT/'outputs',PROJECT_ROOT/'datasets')):
                raise ValueError('Select a folder under outputs/ or datasets/')
            refresh(p,base,settings['token'])
            reports=list(p.glob('*/RUN_REPORT.md'))+list(p.glob('trials/*/RUN_REPORT.md'))
            for report in reports:refresh(report.parent,base,settings['token'])
        if not folder and not dataset:
            for report in (PROJECT_ROOT/'outputs/simulator_runs').glob('*/*/RUN_REPORT.md'):
                refresh(report.parent,base,settings['token'])
        print(f'Replay launcher ready at {base}. Dataset indexes and sweep reports refreshed.',flush=True)
        print('Keep this running; click ▶ Replay or ▶ Action Replay. Both start automatically. Ctrl+C stops the launcher.',flush=True)
        try:server.serve_forever()
        except KeyboardInterrupt:pass


def main():
    p=argparse.ArgumentParser(description=__doc__)
    p.add_argument('--sweep',type=Path,help='Refresh a specific sweep (default: all local indexes)')
    p.add_argument('--dataset',type=Path,help='Refresh a specific dataset')
    p.add_argument('--port',type=int,help='Local port (default: saved workspace port)');a=p.parse_args()
    serve(a.sweep,a.port,a.dataset)

if __name__=='__main__':main()
